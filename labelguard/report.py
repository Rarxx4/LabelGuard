"""Self-contained HTML report (annotated artwork + findings), for sharing with designers / approvers."""
from __future__ import annotations

import base64
import html
import io

from .schemas import RunResult, Verdict
from .trust import readiness
from .viz import annotate

BADGE = {Verdict.FAIL: "#d62828", Verdict.NEEDS_REVIEW: "#e69600", Verdict.PASS: "#229650",
         Verdict.NOT_APPLICABLE: "#828282"}


def _img(pil) -> str:
    buf = io.BytesIO()
    pil.save(buf, "JPEG", quality=85)
    return "data:image/jpeg;base64," + base64.b64encode(buf.getvalue()).decode()


def build_html(run: RunResult) -> str:
    e = html.escape
    r = readiness(run.findings)
    color = {"not_ready": "#d62828", "review": "#e69600", "ready": "#229650"}[r["status"]]
    pages = "".join(f'<img src="{_img(annotate(p, run.findings))}" alt="Artwork page {p.index + 1}">'
                    for p in run.pages)
    rows = []
    for f in run.findings:
        if f.verdict == Verdict.NOT_APPLICABLE:
            continue
        ev = "<br>".join(
            f"{'✔' if x.verified else '✖'} <i>{e(x.source)}</i>: “{e(x.quote[:160])}”" for x in f.evidence if x.quote)
        notes = "<br>".join(e(n) for n in f.trust_notes)
        review = ""
        if f.review_decision:
            review = f"<br><b>Reviewer:</b> {e(f.review_decision)} {e(f.review_note)}"
        rows.append(
            f"<tr><td><b>{f.finding_id}</b></td>"
            f"<td><span class='b' style='background:{BADGE[f.verdict]}'>{f.verdict.value.replace('_', ' ')}</span>"
            f"<br><small>{e(f.severity)} · conf {f.confidence:.2f}</small></td>"
            f"<td><b>{e(f.rule_id)} {e(f.title)}</b><br>{e(f.summary)}"
            f"<br><small><b>Expected:</b> {e(f.expected)}<br><b>Found:</b> {e(f.found)}</small>"
            f"{'<br><small><b>Fix:</b> ' + e(f.suggested_fix) + '</small>' if f.suggested_fix else ''}{review}</td>"
            f"<td><small>{ev}</small></td><td><small>{notes}</small></td></tr>")
    return f"""<!doctype html><html><head><meta charset="utf-8"><title>LabelGuard report - {e(run.artwork_name)}</title>
<style>
body{{font-family:Segoe UI,Arial,sans-serif;margin:24px;color:#1d1d1f}}
.v{{display:inline-block;padding:10px 18px;border-radius:8px;color:#fff;font-weight:700;background:{color}}}
img{{max-width:100%;border:1px solid #ddd;margin:12px 0}}
table{{border-collapse:collapse;width:100%}}td,th{{border-bottom:1px solid #e5e5e5;padding:8px;vertical-align:top;text-align:left}}
.b{{color:#fff;padding:2px 8px;border-radius:4px;font-size:12px;font-weight:600}}small{{color:#444}}
</style></head><body>
<h1>LabelGuard pre-flight report</h1>
<p><b>Artwork:</b> {e(run.artwork_name)} &nbsp; <b>Rules:</b> {e(', '.join(run.rulebook_names))} &nbsp;
<b>Spec:</b> {e(run.spec_name or '-')} &nbsp; <b>Market:</b> {e(run.market)} &nbsp; <b>Run:</b> {run.run_id} ({e(run.model)})</p>
<div class="v">{r['label']}</div>
<p>{r['fail']} failing · {r['review']} need review · {r['pass']} passing · {r['dismissed']} dismissed by reviewer ·
{r['adjusted']} AI verdicts adjusted by the trust layer</p>
{pages}
<table><tr><th>ID</th><th>Verdict</th><th>Finding</th><th>Evidence (✔ = verified on source)</th><th>Trust notes</th></tr>
{''.join(rows)}</table>
<p><small>Generated by LabelGuard. AI findings are decision support; a qualified reviewer must approve artwork before print.</small></p>
</body></html>"""
